-- DJIHS Management System: database schema
-- Derived from the queries in app/lib/data.js, app/lib/seed.js, app/lib/reports.js
-- and the pages that call Supabase directly. No RLS: the app uses the anon key
-- for every query and does its own auth (bcrypt + user_id cookie).
--
-- Column names are all-lowercase without underscores (firstname, sectionid, ...)
-- except where the code uses snake_case (users.first_name, system_config.*, ...).
-- PostgREST embeds (e.g. classes -> teachers) rely on the foreign keys below.

create extension if not exists pgcrypto;

-- ---------------------------------------------------------------------------
-- users: login accounts (registrar, key teacher, subject teacher)
-- ---------------------------------------------------------------------------
create table public.users (
  id          uuid primary key default gen_random_uuid(),
  username    text not null unique,
  password    text not null,                       -- bcrypt hash
  role        text not null
              check (role in ('registrar', 'key teacher', 'subject teacher')),
  first_name  text,
  last_name   text,
  email       text,                                -- joins to teachers.email
  phone       text,
  created_at  timestamptz not null default now()
);

-- ---------------------------------------------------------------------------
-- teachers: teaching staff; linked to users by email
-- ---------------------------------------------------------------------------
create table public.teachers (
  teacherid   bigint generated by default as identity primary key,
  firstname   text not null,
  lastname    text not null,
  email       text unique,
  phone       text,
  created_at  timestamptz not null default now()
);

-- ---------------------------------------------------------------------------
-- schoolyears
-- ---------------------------------------------------------------------------
create table public.schoolyears (
  sy_id       bigint generated by default as identity primary key,
  yearrange   text not null unique                 -- e.g. '2025-26'
);

-- ---------------------------------------------------------------------------
-- sections: one advisory class per section
-- ---------------------------------------------------------------------------
create table public.sections (
  sectionid   bigint generated by default as identity primary key,
  sectionname text not null,
  gradelevel  smallint not null check (gradelevel between 7 and 10),
  adviserid   bigint unique references public.teachers (teacherid) on delete set null,
  status      text not null default 'Active',
  unique (gradelevel, sectionname)
);

-- ---------------------------------------------------------------------------
-- subjects
-- ---------------------------------------------------------------------------
create table public.subjects (
  subjectcode        text primary key,             -- e.g. 'MATH7'
  subjectname        text not null,
  intendedgradelevel smallint not null check (intendedgradelevel between 7 and 10)
);

-- ---------------------------------------------------------------------------
-- students
-- ---------------------------------------------------------------------------
create table public.students (
  lrn           text primary key,                  -- 12-digit Learner Reference Number
  firstname     text not null,
  lastname      text not null,
  middleinitial text,
  birthday      date,
  address       text,
  email         text,
  gender        text,                              -- written by the Excel import
  sex           text generated always as (gender) stored,  -- read by the SF9 grade modal
  sectionid     bigint references public.sections (sectionid) on delete set null,  -- written by the Excel import
  created_at    timestamptz not null default now()
);

-- ---------------------------------------------------------------------------
-- enrollments: a student in a section for a school year
-- ---------------------------------------------------------------------------
create table public.enrollments (
  enrollmentid bigint generated by default as identity primary key,
  lrn          text not null references public.students (lrn) on update cascade on delete cascade,
  sectionid    bigint references public.sections (sectionid) on delete set null,
  sy_id        bigint not null references public.schoolyears (sy_id),
  gradelevel   smallint not null check (gradelevel between 7 and 10),
  status       text not null default 'Enrolled',  -- Enrolled | Dropped | Inactive | Transferred | Graduated
  created_at   timestamptz not null default now(),
  unique (lrn, sy_id)
);

create index enrollments_sectionid_idx on public.enrollments (sectionid);
create index enrollments_sy_id_idx on public.enrollments (sy_id);

-- ---------------------------------------------------------------------------
-- classes: a subject taught by a teacher to a section, plus per-quarter workflow
--   qN_submission_status: subject teacher's state   (null | 'forwarded')
--   qN_status:            key teacher's verification (null | 'review' | 'completed' | 'resubmitted' | 'submitted')
-- ---------------------------------------------------------------------------
create table public.classes (
  classid     bigint generated by default as identity primary key,
  subjectcode text not null references public.subjects (subjectcode) on update cascade on delete cascade,
  teacherid   bigint references public.teachers (teacherid) on delete set null,
  sectionid   bigint not null references public.sections (sectionid) on delete cascade,
  schedule    text,

  q1_submission_status text,
  q2_submission_status text,
  q3_submission_status text,
  q4_submission_status text,

  q1_status text,
  q2_status text,
  q3_status text,
  q4_status text,

  last_submitted timestamptz,
  unique (subjectcode, teacherid, sectionid)
);

create index classes_teacherid_idx on public.classes (teacherid);
create index classes_sectionid_idx on public.classes (sectionid);

-- ---------------------------------------------------------------------------
-- grades: one row per enrollment x class x quarter
-- ---------------------------------------------------------------------------
create table public.grades (
  gradeid         bigint generated by default as identity primary key,
  enrollmentid    bigint not null references public.enrollments (enrollmentid) on delete cascade,
  classid         bigint not null references public.classes (classid) on delete cascade,
  quarter         smallint not null check (quarter between 1 and 4),
  writtenwork     numeric(5,2),
  performancetask numeric(5,2),
  finalgrade      numeric(5,2),
  remarks         text,                            -- 'PASSED' | 'FAILED' | 'PENDING'
  unique (enrollmentid, classid, quarter)          -- target of saveGradesToDb upsert
);

create index grades_classid_quarter_idx on public.grades (classid, quarter);

-- saveGradesToDb upserts a batch where some rows carry gradeid and some don't.
-- supabase-js sends the missing ones as explicit NULL, so fill them from the
-- sequence on insert, and never let an upsert rewrite an existing gradeid.
create or replace function public.grades_keep_gradeid()
returns trigger
language plpgsql
as $$
begin
  if tg_op = 'INSERT' then
    if new.gradeid is null then
      new.gradeid := nextval(pg_get_serial_sequence('public.grades', 'gradeid'));
    end if;
  else
    new.gradeid := old.gradeid;
  end if;
  return new;
end;
$$;

create trigger grades_keep_gradeid
before insert or update on public.grades
for each row execute function public.grades_keep_gradeid();

-- ---------------------------------------------------------------------------
-- attendance: monthly totals per enrollment (month = full English name, e.g. 'October')
-- ---------------------------------------------------------------------------
create table public.attendance (
  attendanceid    bigint generated by default as identity primary key,
  enrollmentid    bigint not null references public.enrollments (enrollmentid) on delete cascade,
  month           text not null,
  dayspresent     integer not null default 0 check (dayspresent >= 0),
  totalschooldays integer not null default 20 check (totalschooldays >= 0),
  unique (enrollmentid, month)
);

-- ---------------------------------------------------------------------------
-- attendance_logs: daily present/absent/excused marks
-- ---------------------------------------------------------------------------
create table public.attendance_logs (
  id              bigint generated by default as identity primary key,
  attendance_date date not null,
  enrollmentid    bigint not null references public.enrollments (enrollmentid) on delete cascade,
  classid         bigint references public.classes (classid) on delete set null,
  status          text not null check (status in ('present', 'absent', 'excused')),
  created_at      timestamptz not null default now(),
  unique (attendance_date, enrollmentid)           -- target of the attendance upsert
);

create index attendance_logs_classid_date_idx on public.attendance_logs (classid, attendance_date);

-- ---------------------------------------------------------------------------
-- system_config: single row (id = 1) of global settings
-- ---------------------------------------------------------------------------
create table public.system_config (
  id                 integer primary key default 1 check (id = 1),
  active_sy          text not null default '2025-26',
  q1_deadline        date,
  q2_deadline        date,
  q3_deadline        date,
  q4_deadline        date,
  is_editing_enabled boolean not null default true
);

-- ---------------------------------------------------------------------------
-- audit_logs
-- ---------------------------------------------------------------------------
create table public.audit_logs (
  id                bigint generated by default as identity primary key,
  created_at        timestamptz not null default now(),
  action            text not null,
  performed_by_name text,
  target_id         text,
  details           text
);

create index audit_logs_created_at_idx on public.audit_logs (created_at desc);
